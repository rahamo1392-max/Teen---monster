-- TEEN MONSTER starter database schema for Supabase
-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'fan' check (role in ('fan','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  author_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.news enable row level security;
alter table public.messages enable row level security;

drop policy if exists "profiles readable by signed in users" on public.profiles;
create policy "profiles readable by signed in users" on public.profiles for select to authenticated using (true);
drop policy if exists "users create own profile" on public.profiles;
create policy "users create own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
drop policy if exists "users update own display name" on public.profiles;
create policy "users update own display name" on public.profiles for update to authenticated using (auth.uid() = id and role = 'fan') with check (auth.uid() = id and role = 'fan');

drop policy if exists "news readable by everyone" on public.news;
create policy "news readable by everyone" on public.news for select to anon, authenticated using (true);
drop policy if exists "admins publish news" on public.news;
create policy "admins publish news" on public.news for insert to authenticated with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

drop policy if exists "messages readable by signed in users" on public.messages;
create policy "messages readable by signed in users" on public.messages for select to authenticated using (true);
drop policy if exists "signed in users send own messages" on public.messages;
create policy "signed in users send own messages" on public.messages for insert to authenticated with check (auth.uid() = user_id);

-- Create a profile row for each new account.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name, role)
  values (new.id, split_part(new.email, '@', 1), 'fan')
  on conflict (id) do nothing;
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

